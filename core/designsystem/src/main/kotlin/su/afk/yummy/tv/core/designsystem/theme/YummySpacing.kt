package su.afk.yummy.tv.core.designsystem.theme

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/**
 * Shared spacing scale for YANIME UI. Prefer these semantic values over local dp literals
 * when composing reusable surfaces, cards, lists and screen layouts.
 */
object YummySpacing {
    val None: Dp = 0.dp
    val XSmall: Dp = 4.dp
    val Small: Dp = 8.dp
    val Medium: Dp = 12.dp
    val Large: Dp = 16.dp
    val XLarge: Dp = 20.dp
    val XXLarge: Dp = 24.dp
    val XXXLarge: Dp = 32.dp
    val Section: Dp = 40.dp
    val ScreenHorizontal: Dp = 20.dp
    val TvScreenHorizontal: Dp = 56.dp
    val TouchTarget: Dp = 48.dp
    val TvTouchTarget: Dp = 56.dp
}
